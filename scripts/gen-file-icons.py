#!/usr/bin/env python3
"""Regenerate the file-icon tables from the Material Icon Theme npm package.

    npm pack material-icon-theme && tar xzf material-icon-theme-*.tgz
    scripts/gen-file-icons.py package

Copies every referenced SVG into crates/veloce/assets/file-icons/ and writes
crates/veloce/src/file_icons_data.rs (sorted tables, so lookups can binary-search).
"""
import json, shutil, sys


def lit(text):
    """Rust string literal (json.dumps emits \\uXXXX pairs that Rust rejects)."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

from pathlib import Path

pkg = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
assets = root / "crates/veloce/assets/file-icons"
theme = json.loads((pkg / "dist/material-icons.json").read_text())

tables = {
    "FILE_EXTENSIONS": theme["fileExtensions"],
    "FILE_NAMES": theme["fileNames"],
    "FOLDER_NAMES": theme["folderNames"],
    "FOLDER_NAMES_EXPANDED": theme["folderNamesExpanded"],
}
defaults = [theme["file"], theme["folder"], theme["folderExpanded"]]

used = set(defaults)
for table in tables.values():
    used.update(table.values())
used = {i for i in used if (pkg / "icons" / f"{i}.svg").exists()}

shutil.rmtree(assets, ignore_errors=True)
assets.mkdir(parents=True)
for icon in sorted(used):
    shutil.copy(pkg / "icons" / f"{icon}.svg", assets / f"{icon}.svg")
shutil.copy(pkg / "LICENSE", assets / "LICENSE-material-icon-theme.txt")

out = ["// @generated by scripts/gen-file-icons.py — do not edit.", ""]
out.append(f'pub const DEFAULT_FILE: &str = "{theme["file"]}";')
out.append(f'pub const DEFAULT_FOLDER: &str = "{theme["folder"]}";')
out.append(f'pub const DEFAULT_FOLDER_OPEN: &str = "{theme["folderExpanded"]}";')
out.append("")
for name, table in tables.items():
    rows = sorted((k.lower(), v) for k, v in table.items() if v in used)
    out.append(f"pub static {name}: &[(&str, &str)] = &[")
    out += [f'    ({lit(k)}, {lit(v)}),' for k, v in rows]
    out.append("];\n")
out.append("pub static ASSETS: &[(&str, &[u8])] = &[")
for icon in sorted(used):
    out.append(f'    ("{icon}", include_bytes!("../assets/file-icons/{icon}.svg")),')
out.append("];")
(root / "crates/veloce/src/file_icons_data.rs").write_text("\n".join(out) + "\n")
print(len(used), "icons")
